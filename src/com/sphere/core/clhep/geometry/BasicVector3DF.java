package com.sphere.core.clhep.geometry;

import com.sphere.core.clhep.CMath;
import com.sphere.core.clhep.vector.Hep3Vector;
import com.sphere.core.hepmc3.cxx.CIStream;
import com.sphere.core.hepmc3.cxx.COStream;
import com.sphere.core.hepmc3.cxx.StdStreams;

/**
 * CLHEP's HepGeom::BasicVector3D&lt;float&gt; (Geometry/BasicVector3D.h, BasicVector3D.cc): three
 * coordinates and what Point3D, Vector3D and Normal3D share — lengths, angles, rotations, the arithmetic
 * of the free operators (+, -, * by a number, * as the dot product, /).
 *
 * <p>In float as the C++ specialisation computes: its coordinates' arithmetic in float, std::sqrt,
 * atan2, sin, cos, log and exp of a float the C library's float functions, the rotations and setEta
 * in double, rounded to float when stored.
 * Generated by gen_geometry.py.
 */
public class BasicVector3DF {

    public static final int X = 0;
    public static final int Y = 1;
    public static final int Z = 2;
    public static final int NUM_COORDINATES = 3;
    public static final int SIZE = NUM_COORDINATES;

    protected final float[] v_ = new float[3];

    /** (0,0,0): protected in C++, where only Point3D, Vector3D and Normal3D make it. */
    protected BasicVector3DF() {
    }

    public BasicVector3DF(float x1, float y1, float z1) {
        v_[0] = x1;
        v_[1] = y1;
        v_[2] = z1;
    }

    public BasicVector3DF(BasicVector3DF v) {
        v_[0] = v.v_[0];
        v_[1] = v.v_[1];
        v_[2] = v.v_[2];
    }

    /** operator T*: the coordinates themselves. */
    public float[] data() {
        return v_;
    }

    /** operator Hep3Vector. */
    public Hep3Vector toHep3Vector() {
        return new Hep3Vector(x(), y(), z());
    }

    /** operator=. */
    public BasicVector3DF assign(BasicVector3DF v) {
        v_[0] = v.v_[0];
        v_[1] = v.v_[1];
        v_[2] = v.v_[2];
        return this;
    }

    public BasicVector3DF plusAssign(BasicVector3DF v) {
        v_[0] += v.v_[0];
        v_[1] += v.v_[1];
        v_[2] += v.v_[2];
        return this;
    }

    public BasicVector3DF minusAssign(BasicVector3DF v) {
        v_[0] -= v.v_[0];
        v_[1] -= v.v_[1];
        v_[2] -= v.v_[2];
        return this;
    }

    /** operator*=(double): each coordinate times a, in double, stored as float. */
    public BasicVector3DF timesAssign(double a) {
        v_[0] *= a;
        v_[1] *= a;
        v_[2] *= a;
        return this;
    }

    public BasicVector3DF divAssign(double a) {
        v_[0] /= a;
        v_[1] /= a;
        v_[2] /= a;
        return this;
    }

    /** operator() and operator[]. */
    public float get(int i) {
        return v_[i];
    }

    /** The coordinate i set (T&amp; operator[]). */
    public void set(int i, float a) {
        v_[i] = a;
    }

    public float x() {
        return v_[0];
    }

    public float y() {
        return v_[1];
    }

    public float z() {
        return v_[2];
    }

    public void setX(float a) {
        v_[0] = a;
    }

    public void setY(float a) {
        v_[1] = a;
    }

    public void setZ(float a) {
        v_[2] = a;
    }

    public void set(float x1, float y1, float z1) {
        v_[0] = x1;
        v_[1] = y1;
        v_[2] = z1;
    }

    public float perp2() {
        return x() * x() + y() * y();
    }

    public float perp() {
        return CMath.sqrtf(perp2());
    }

    public float rho() {
        return perp();
    }

    public void setPerp(float rh) {
        float factor = perp();
        if (factor > 0) {
            factor = rh / factor;
            v_[0] *= factor;
            v_[1] *= factor;
        }
    }

    public float mag2() {
        return x() * x() + y() * y() + z() * z();
    }

    public float mag() {
        return CMath.sqrtf(mag2());
    }

    public float r() {
        return mag();
    }

    public float phi() {
        return x() == 0 && y() == 0 ? 0 : CMath.atan2f(y(), x());
    }

    public float theta() {
        return x() == 0 && y() == 0 && z() == 0 ? 0 : CMath.atan2f(perp(), z());
    }

    public float cosTheta() {
        final float ma = mag();
        return ma == 0 ? 1 : z() / ma;
    }

    public float getR() {
        return r();
    }

    public float getPhi() {
        return phi();
    }

    public float getTheta() {
        return theta();
    }

    public void setMag(float ma) {
        float factor = mag();
        if (factor > 0) {
            factor = ma / factor;
            v_[0] *= factor;
            v_[1] *= factor;
            v_[2] *= factor;
        }
    }

    public void setR(float ma) {
        setMag(ma);
    }

    public void setPhi(float ph) {
        final float xy = perp();
        setX(xy * CMath.cosf(ph));
        setY(xy * CMath.sinf(ph));
    }

    public void setTheta(float th) {
        final float ma = mag();
        final float ph = phi();
        set(ma * CMath.sinf(th) * CMath.cosf(ph), ma * CMath.sinf(th) * CMath.sinf(ph), ma * CMath.cosf(th));
    }

    /** -log(tan(theta/2)); Float.MAX_VALUE along the axis, 0 for the null vector. */
    public float pseudoRapidity() {
        final float ma = mag();
        final float dz = z();
        if (ma == 0) return 0;
        if (ma == dz) return Float.MAX_VALUE;
        if (ma == -dz) return -Float.MAX_VALUE;
        return (float) (0.5 * CMath.logf((ma + dz) / (ma - dz)));
    }

    public float eta() {
        return pseudoRapidity();
    }

    public float getEta() {
        return pseudoRapidity();
    }

    public void setEta(float a) {
        final double ma = mag();
        if (ma == 0) return;
        final double tanHalfTheta = CMath.expf(-a);
        final double tanHalfTheta2 = tanHalfTheta * tanHalfTheta;
        final double cosTheta1 = (1 - tanHalfTheta2) / (1 + tanHalfTheta2);
        final double rh = ma * Math.sqrt(1 - cosTheta1 * cosTheta1);
        final double ph = phi();
        set((float) (rh * CMath.cos(ph)), (float) (rh * CMath.sin(ph)), (float) (ma * cosTheta1));
    }

    public float dot(BasicVector3DF v) {
        return x() * v.x() + y() * v.y() + z() * v.z();
    }

    public BasicVector3DF cross(BasicVector3DF v) {
        return new BasicVector3DF(y() * v.z() - v.y() * z(),
            z() * v.x() - v.z() * x(),
            x() * v.y() - v.x() * y());
    }

    /** The square of the component perpendicular to v. */
    public float perp2(BasicVector3DF v) {
        final float tot = v.mag2();
        final float s = dot(v);
        return tot > 0 ? mag2() - s * s / tot : mag2();
    }

    public float perp(BasicVector3DF v) {
        return CMath.sqrtf(perp2(v));
    }

    public float angle(BasicVector3DF v) {
        double cosa = 0;
        final double ptot = mag() * v.mag();
        if (ptot > 0) {
            cosa = dot(v) / ptot;
            if (cosa > 1) cosa = 1;
            if (cosa < -1) cosa = -1;
        }
        return (float) (CMath.acos(cosa));
    }

    public BasicVector3DF unit() {
        final float len = mag();
        return (len > 0) ? new BasicVector3DF(x() / len, y() / len, z() / len) : new BasicVector3DF();
    }

    public BasicVector3DF orthogonal() {
        final float dx = x() < 0 ? -x() : x();
        final float dy = y() < 0 ? -y() : y();
        final float dz = z() < 0 ? -z() : z();
        if (dx < dy) {
            return dx < dz ? new BasicVector3DF(0, z(), -y()) : new BasicVector3DF(y(), -x(), 0);
        } else {
            return dy < dz ? new BasicVector3DF(-z(), 0, x()) : new BasicVector3DF(y(), -x(), 0);
        }
    }

    public BasicVector3DF rotateX(float a) {
        final double sina = CMath.sinf(a);
        final double cosa = CMath.cosf(a);
        final double dy = y();
        final double dz = z();
        setY((float) (dy * cosa - dz * sina));
        setZ((float) (dz * cosa + dy * sina));
        return this;
    }

    public BasicVector3DF rotateY(float a) {
        final double sina = CMath.sinf(a);
        final double cosa = CMath.cosf(a);
        final double dz = z();
        final double dx = x();
        setZ((float) (dz * cosa - dx * sina));
        setX((float) (dx * cosa + dz * sina));
        return this;
    }

    public BasicVector3DF rotateZ(float a) {
        final double sina = CMath.sinf(a);
        final double cosa = CMath.cosf(a);
        final double dx = x();
        final double dy = y();
        setX((float) (dx * cosa - dy * sina));
        setY((float) (dy * cosa + dx * sina));
        return this;
    }

    /** A rotation by a around the axis v. */
    public BasicVector3DF rotate(float a, BasicVector3DF v) {
        if (a == 0) return this;
        double cx = v.x();
        double cy = v.y();
        double cz = v.z();
        final double ll = Math.sqrt(cx * cx + cy * cy + cz * cz);
        if (ll == 0) {
            StdStreams.cerr().print("BasicVector<float>::rotate() : zero axis\n");
            return this;
        }
        final double cosa = CMath.cosf(a);
        final double sina = CMath.sinf(a);
        cx /= ll;
        cy /= ll;
        cz /= ll;
        final double xx = cosa + (1 - cosa) * cx * cx;
        final double xy = (1 - cosa) * cx * cy - sina * cz;
        final double xz = (1 - cosa) * cx * cz + sina * cy;
        final double yx = (1 - cosa) * cy * cx + sina * cz;
        final double yy = cosa + (1 - cosa) * cy * cy;
        final double yz = (1 - cosa) * cy * cz - sina * cx;
        final double zx = (1 - cosa) * cz * cx - sina * cy;
        final double zy = (1 - cosa) * cz * cy + sina * cx;
        final double zz = cosa + (1 - cosa) * cz * cz;
        cx = x();
        cy = y();
        cz = z();
        set((float) (xx * cx + xy * cy + xz * cz), (float) (yx * cx + yy * cy + yz * cz),
            (float) (zx * cx + zy * cy + zz * cz));
        return this;
    }

    /* ---- the free operators ---- */

    /** +v: a copy. */
    public BasicVector3DF plus() {
        return new BasicVector3DF(this);
    }

    public BasicVector3DF plus(BasicVector3DF b) {
        return new BasicVector3DF(x() + b.x(), y() + b.y(), z() + b.z());
    }

    public BasicVector3DF negate() {
        return new BasicVector3DF(-x(), -y(), -z());
    }

    public BasicVector3DF minus(BasicVector3DF b) {
        return new BasicVector3DF(x() - b.x(), y() - b.y(), z() - b.z());
    }

    /** v * a (a float first). */
    public BasicVector3DF times(double a) {
        return new BasicVector3DF(x() * (float) a, y() * (float) a, z() * (float) a);
    }

    /** a * v. */
    public static BasicVector3DF times(double a, BasicVector3DF v) {
        return new BasicVector3DF((float) a * v.x(), (float) a * v.y(), (float) a * v.z());
    }

    /** v * w: the dot product. */
    public float times(BasicVector3DF b) {
        return dot(b);
    }

    public BasicVector3DF div(double a) {
        return new BasicVector3DF(x() / (float) a, y() / (float) a, z() / (float) a);
    }

    /** operator==: the same coordinates. */
    public boolean isEqual(BasicVector3DF b) {
        return x() == b.x() && y() == b.y() && z() == b.z();
    }

    public boolean notEqual(BasicVector3DF b) {
        return x() != b.x() || y() != b.y() || z() != b.z();
    }

    @Override
    public boolean equals(Object o) {
        return o instanceof BasicVector3DF b && isEqual(b);
    }

    @Override
    public int hashCode() {
        return java.util.Arrays.hashCode(v_);
    }

    /** operator&lt;&lt;: (x,y,z). */
    public COStream print(COStream os) {
        return os.put("(").put(x()).put(",").put(y()).put(",").put(z()).put(")");
    }

    /** operator&gt;&gt;: (x,y,z); what is wrong said on cerr. */
    public static CIStream read(CIStream is, BasicVector3DF a) {
        int c = is.nextChar();
        if (is.fail() || c != '(') {
            StdStreams.cerr().print("Could not find required opening parenthesis in input of a BasicVector3D<float>\n");
            return is;
        }
        final float x = is.nextFloat();
        c = is.nextChar();
        if (is.fail() || c != ',') {
            StdStreams.cerr().print("Could not find x value and required trailing comma in input of a BasicVector3D<float>\n");
            return is;
        }
        final float y = is.nextFloat();
        c = is.nextChar();
        if (is.fail() || c != ',') {
            StdStreams.cerr().print("Could not find y value and required trailing comma in input of a BasicVector3D<float>\n");
            return is;
        }
        final float z = is.nextFloat();
        c = is.nextChar();
        if (is.fail() || c != ')') {
            StdStreams.cerr().print("Could not find z value and required close parenthesis in input of a BasicVector3D<float>\n");
            return is;
        }
        a.setX(x);
        a.setY(y);
        a.setZ(z);
        return is;
    }

    @Override
    public String toString() {
        return print(new COStream()).str();
    }
}
