    private static long bits(double x) {
        return Double.doubleToRawLongBits(x);
    }

    private void v3(String n, double x, double y, double z) {
        line(String.format(Locale.ROOT, "%s %016x %016x %016x", n, bits(x), bits(y), bits(z)));
    }

    private void pv(String n, BasicVector3D v) {
        v3(n, v.x(), v.y(), v.z());
    }

    private void pv(String n, BasicVector3DF v) {
        v3(n, v.x(), v.y(), v.z());
    }

    private void pl(String n, Plane3D p) {
        line(String.format(Locale.ROOT, "%s %016x %016x %016x %016x", n, bits(p.a()), bits(p.b()), bits(p.c()), bits(p.d())));
    }

    private void pl(String n, Plane3DF p) {
        line(String.format(Locale.ROOT, "%s %016x %016x %016x %016x", n, bits(p.a()), bits(p.b()), bits(p.c()), bits(p.d())));
    }

    private void pt(String n, Transform3D t) {
        final StringBuilder b = new StringBuilder(n);
        for (int r = 0; r < 3; r++) {
            for (int c = 0; c < 4; c++) b.append(String.format(Locale.ROOT, " %016x", bits(t.get(r, c))));
        }
        line(b.toString());
    }

