            pt(n + ".t2", t2);
            pt(n + ".t12", t1.times(t2));
            pt(n + ".inv1", t1.inverse());
            pt(n + ".inv2", t2.inverse());
            pt(n + ".invinv", t1.inverse().inverse());
            i(n + ".near", t1.isNear(t1.inverse().inverse()));
