            pt(n + ".rotx", new RotateX3D(a));
            pt(n + ".roty", new RotateY3D(b));
            pt(n + ".rotz", new RotateZ3D(g));
            pt(n + ".tra", new Translate3D(c[0], c[1], c[2]));
            pt(n + ".trav", new Translate3D(new Hep3Vector(c[3], c[4], c[5])));
